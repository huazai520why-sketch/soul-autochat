def _vm_index():
    import os
    raw = (os.environ.get("SOUL_VMINDEX") or "").strip()
    if not raw.isdigit():
        return 0
    v = int(raw)
    return v if v in IDENT_TABLE else 0


def ident():
    return IDENT_TABLE[_vm_index()]


# ── ① 身份 ─────────────────────────────────────────────────
