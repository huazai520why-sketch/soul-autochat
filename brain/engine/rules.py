# ── ⑥ 输出规格 ───────────────────────────────────────────────
# 改动：删掉「这一轮必须带一个具体问题（她一句话就能答的），整轮只有一个问句；
#       上一条你已经在问，这条就不许再问。」
# 为什么错（三条实测，不是判断）：
#   ① 无效：带问号她回 5.5 字 / 不带问号 4.9 字，差 0.6 字 —— 提问买不到字数。
#   ② 反向：她 52.8% 只回 ≤4 字；她越短我越长（她 ≤2 字后我平均 12.1 字），
#      而这条规则规定「必须问」，等于把「加码」写成了义务。
#   ③ 有病：强制问 → 只能问出「吃了没/在干嘛」这种她答 2 个字就完事的问题，
#      回合数涨、信息量不涨，这就是用户说的「聊了很久没进展」。
# 现在：提问降级为「三种收尾之一」，且她敷衍时**明令禁止**提问。
OUTPUT_SPEC = (
    "【输出】只输出要发给她的那一两句话：口语、像人话；两句就分两行，"
    "别堆成一大段。不要解释、不要编号、不要分析、不要引号。\n"
    "· **提问不是义务，追问才是病。**这一轮带不带问句，按她那条来定：\n"
    "  ├ 她这条是问句 → 先把问题答完；答完可以不带问句（答完就是一次完整的回合）。\n"
    "  ├ 她这条是陈述 / 分享 / 长句（≥8 字）→ 可以带问句，也可以只接情绪 + 说自己的。\n"
    "  ├ 她这条 ≤4 字（嗯/哦/好/哈哈/切/。。）→ **禁止提问**，一条、8 字以内，说完就停。\n"
    "  └ 上一条你已经在问、她没答 → 这条绝对不许再问同一个意思。\n"
    "· 整轮问句最多一个；她敷衍时是零个。\n"
    "档案里的信息只当背景，别当面点破（不许说「你主页写着…」），"
    "也不许把没聊过的事说成她说过；她提过的细节隔几轮可以自然带一句，同一件只提一次。"
)


# ── ⑦ 每日策略回流（2026-11-13 新增）──────────────────────────
# 每天 23:50 会诊产出 strategy.md → 落到 data/state/daily_strategy.md → 这里读进来挂进 prompt。
# 文件不存在或空 → 返回 None，system_blocks 跳过，不影响运行。
def daily_strategy():
    """读当日复盘策略（data/state/daily_strategy.md），返回文本块或 None。"""
    import os
    p = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                     "data", "state", "daily_strategy.md")
    try:
        with open(p, encoding="utf-8") as f:
            txt = f.read().strip()
        if not txt:
            return None
        return "【今日复盘策略·临时】\n" + txt
    except Exception:
        return None


def head_blocks():
    """规则块（不含人设），顺序与拆分前 persona.system_blocks() 的第 2~6 块一致。"""
    blocks = [voice(), PRIORITY, CRAFT, ADVANCE, HARD]
    ds = daily_strategy()  # 每日策略（存在才挂，不存在跳过）
    if ds:
        blocks.append(ds)
    return blocks


def system_blocks():
    """完整固定前缀：人设 1 块 + 规则 5 块（+ 每日策略 1 块，存在才挂）。

    与拆分前旧 persona.system_blocks() **逐字等价**（顺序、分隔都不变），
    prompt.build 只要把调用从 persona.system_blocks() 换成这里即可。
    """
    return persona.system_blocks() + head_blocks()


def chars():
    """规则总字数（5 块 + 输出规格；自检用）。"""
    return sum(len(x) for x in head_blocks()) + len(OUTPUT_SPEC)


